import type { GitHubService } from '../github.service';

/**
 * Creating a test PR from an accepted draft.
 *
 * This is the only place Phase 5 writes to GitHub, so the rules are strict:
 *
 *  - a new branch is created from the *recorded* base SHA — never the source
 *    branch, and never `main` directly;
 *  - the base is re-read first, and a moved base is a hard stop, not a silent
 *    apply;
 *  - the whole thing is idempotent from the client's point of view: a retried
 *    request that already opened a PR returns that PR, and re-committing the
 *    same content is a no-op.
 *
 * Nothing here executes code. The only inputs are a path (already validated by
 * the caller) and a string body.
 */

export type TestPrErrorCode =
  | 'confirmation-required'
  | 'stale-base'
  | 'base-branch-missing'
  | 'github-error'
  | 'write-disabled';

export class TestPrError extends Error {
  constructor(
    public readonly code: TestPrErrorCode,
    message: string,
  ) {
    super(message);
    this.name = 'TestPrError';
  }
}

export interface TestPrDraftInput {
  id: string;
  /** Already validated repo-relative test path. */
  targetPath: string;
  /** Already validated text content. */
  targetContent: string;
  /** Source file the test covers, for the PR title/body. */
  sourcePath: string;
  baseBranch: string;
  baseSha: string;
  sourcePrNumber?: number | null;
  scenarioLabel?: string;
}

export interface CreateTestPrOptions {
  ghService: Pick<
    GitHubService,
    | 'getBranchHeadSha'
    | 'createBranch'
    | 'upsertFile'
    | 'getFileContent'
    | 'findPullRequestByHead'
    | 'createPullRequest'
  >;
  owner: string;
  repo: string;
  draft: TestPrDraftInput;
  /** Explicit developer confirmation. Absent/false is refused. */
  confirmed: boolean;
}

export interface CreateTestPrResult {
  branchName: string;
  /** Commit that added the file, or the branch head when it was already there. */
  commitSha: string | null;
  prNumber: number;
  prUrl: string;
  /** True when a previous attempt had already opened the PR. */
  reused: boolean;
}

export const TEST_DRAFT_BRANCH_PREFIX = 'aipr/test-draft-';

/** Deterministic branch name so a retried request targets the same branch. */
export function testDraftBranchName(draftId: string): string {
  const slug = draftId.replace(/[^a-zA-Z0-9]/g, '').slice(0, 12) || 'draft';
  return `${TEST_DRAFT_BRANCH_PREFIX}${slug}`;
}

export function testDraftPrTitle(draft: TestPrDraftInput): string {
  return `test: AI-drafted tests for ${draft.sourcePath}`;
}

/**
 * Human-readable PR body. It states plainly that the code is AI-generated and
 * unverified and that CI has not reported, and links back to the source PR.
 */
export function buildTestPrBody(owner: string, draft: TestPrDraftInput): string {
  const lines = [
    '## AI-drafted tests (unverified)',
    '',
    '> This test was generated by AI from the changed source and the repository context. It has **not been executed** and **CI has not reported a result**. Review it before trusting it.',
    '',
    `- **Covers:** \`${draft.sourcePath}\``,
    ...(draft.scenarioLabel ? [`- **Scenario:** ${draft.scenarioLabel}`] : []),
    `- **File:** \`${draft.targetPath}\``,
    ...(draft.sourcePrNumber ? [`- **Source PR:** #${draft.sourcePrNumber}`] : []),
    '',
    `_Generated by AI PR Reviewer for \`${owner}\`._`,
    '',
    `<!-- aipr-test-draft:${draft.id} -->`,
  ];
  return lines.join('\n');
}

/**
 * Creates (or reuses) a branch + commit + PR for an accepted draft.
 *
 * Throws `TestPrError` with a machine-readable code for every expected failure
 * so the controller can map it to a status without string matching. The draft
 * itself is never mutated here — persistence is the controller's job, which is
 * what lets a failed API call leave the draft intact for retry.
 */
export async function createTestPullRequest(
  options: CreateTestPrOptions,
): Promise<CreateTestPrResult> {
  const { ghService, owner, repo, draft, confirmed } = options;

  if (!confirmed) {
    throw new TestPrError(
      'confirmation-required',
      'Creating a test PR requires explicit confirmation.',
    );
  }

  const branchName = testDraftBranchName(draft.id);
  const head = `${owner}:${branchName}`;

  // Idempotency, step 1: if a previous attempt already opened a PR for this
  // branch, that IS the result. Re-running must not create a second one.
  const existing = await findExistingPr(ghService, owner, repo, head);
  if (existing) {
    return {
      branchName,
      commitSha: null,
      prNumber: existing.number,
      prUrl: existing.htmlUrl,
      reused: true,
    };
  }

  // Staleness: the recorded base must still be where the branch points. If the
  // base moved, applying the draft silently could commit tests against code
  // that no longer exists.
  const currentBase = await safe(() => ghService.getBranchHeadSha(owner, repo, draft.baseBranch));
  if (currentBase === null) {
    throw new TestPrError(
      'base-branch-missing',
      `The base branch "${draft.baseBranch}" no longer exists on ${owner}/${repo}.`,
    );
  }
  if (currentBase !== draft.baseSha) {
    throw new TestPrError(
      'stale-base',
      `The base branch "${draft.baseBranch}" has moved since this draft was generated. Regenerate the draft against the latest base before creating the PR.`,
    );
  }

  // Create the branch off the recorded base only when it is not already there.
  const branchHead = await safe(() => ghService.getBranchHeadSha(owner, repo, branchName));
  if (branchHead === null) {
    await wrap(ghService.createBranch(owner, repo, branchName, draft.baseSha));
  }

  // Idempotency, step 2: only commit when the file is absent or differs.
  const existingContent = await safe(() =>
    ghService.getFileContent(owner, repo, draft.targetPath, branchName),
  );
  let commitSha: string | null = branchHead;
  if (existingContent !== draft.targetContent) {
    commitSha = await wrap(
      ghService.upsertFile(
        owner,
        repo,
        draft.targetPath,
        draft.targetContent,
        `test: add AI-drafted tests for ${draft.sourcePath}`,
        branchName,
      ),
    );
  }

  const pr = await wrap(
    ghService.createPullRequest(
      owner,
      repo,
      testDraftPrTitle(draft),
      branchName,
      draft.baseBranch,
      buildTestPrBody(owner, draft),
    ),
  );

  return { branchName, commitSha, prNumber: pr.number, prUrl: pr.htmlUrl, reused: false };
}

async function findExistingPr(
  ghService: CreateTestPrOptions['ghService'],
  owner: string,
  repo: string,
  head: string,
): Promise<{ number: number; htmlUrl: string } | null> {
  // A transient failure here must fail the request, not fall through to a
  // create — otherwise a blip would open a duplicate PR for an existing branch.
  return wrap(ghService.findPullRequestByHead(owner, repo, head));
}

/** Runs a GitHub call, converting an unexpected error into a coded TestPrError. */
async function wrap<T>(p: Promise<T>): Promise<T> {
  try {
    return await p;
  } catch (err) {
    throw new TestPrError('github-error', (err as Error).message || 'GitHub request failed.');
  }
}

/** Like `wrap`, but returns null instead of throwing — for best-effort lookups. */
async function safe<T>(p: () => Promise<T>): Promise<T | null> {
  try {
    return await p();
  } catch {
    return null;
  }
}

export type { CreateTestPrResult as TestPrResult };
